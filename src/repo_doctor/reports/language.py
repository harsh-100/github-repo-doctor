"""Plain-language text for findings. Curated, deterministic, and deliberately conditional:
we say what the code shows, and only say "could" about consequences. Nothing here is generated by a model."""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import PurePosixPath

from repo_doctor.core.models import Finding, Verification


@dataclass(frozen=True)
class Text:
    title: str   # plain-English headline
    what: str    # what we found
    why: str     # why it matters
    risk: str    # what could happen
    fix: str     # how to fix it
    action: str  # short imperative for the action plan


FIXTURE_DIRS = {"tests", "test", "__tests__", "spec", "specs", "examples", "example", "fixtures", "fixture",
                "sample", "samples", "sample-project", "demo", "demos", "mock", "mocks", "testdata", "e2e"}


def fixture_marker(path: str | None) -> str | None:
    """Name of the test/example folder a file lives in (a hint that values may be intentionally fake)."""
    if not path:
        return None
    parts = PurePosixPath(path).parts
    for part in parts[:-1]:
        if part.lower() in FIXTURE_DIRS:
            return part
    name = parts[-1].lower() if parts else ""
    if name.startswith("test_") or name.endswith(("_test.py", ".test.js", ".test.ts", ".spec.js", ".spec.ts")):
        return "test file"
    return None


_SECRET_NOTE = ("This file is in a test or example location ({where}). If the value is deliberately fake, this is "
                "probably not a real problem. Confirm that, and keep real secrets out of examples.")
_CONTEXT_CATEGORIES = ("security/hardcoded-secret", "security/gitleaks", "security/unsafe-pattern", "security/bandit")


_COMMENT_HINT = re.compile(r"(?:#|//|/\*|--)[^\n]*?\b(fake|dummy|placeholder|example|sample|mock|test(?:ing)?|not real)\b", re.IGNORECASE)
_COMMENT_NOTE = ("A comment next to it calls this value \"{word}\". If it is deliberately fake, this is probably not a "
                 "real problem. Confirm that, and keep real secrets out of examples.")


def context_note(f: Finding) -> str:
    """Why a finding may be harmless (test/example folder, or a comment saying the value is fake)."""
    if not f.category.startswith(_CONTEXT_CATEGORIES):
        return ""
    where = fixture_marker(f.file_path)
    if where:
        return _SECRET_NOTE.format(where=where)
    m = _COMMENT_HINT.search(f.evidence or "")
    return _COMMENT_NOTE.format(word=m.group(1).lower()) if m else ""


VERIFICATION_TEXT = {
    Verification.VERIFIED: ("Confirmed", "Confirmed by a tool or an exact check of the code."),
    Verification.SUPPORTED: ("Likely", "Reported by the AI model. The code it quoted was found in the file, but "
                                       "whether it is a real problem is the model's judgement."),
    Verification.UNVERIFIED: ("Unconfirmed", "Reported by the AI model, but the code it quoted could not be found. "
                                             "Treat it as a hint to look at, not a fact."),
    Verification.SPECULATIVE: ("Speculative", "The reviewer thought this may not be a real problem. It is listed for "
                                              "completeness and is not counted in the totals."),
    Verification.REJECTED: ("Rejected", "Removed after validation or review."),
}


def _loc(f: Finding) -> str:
    return f"`{f.file_path}`" if f.file_path else "the project"


_SECRET_RISK = ("If the value is real, anyone who can read this repository could use it to access the service it "
                "belongs to, which could mean unauthorised use, cost, or data exposure.")
_SECRET_FIX = ("Check whether the value is real. If it is, revoke or rotate it first (removing it from the code is "
               "not enough), then load it from an environment variable or a secret store. If it is only a "
               "placeholder, use an obviously fake value.")

_EXEC_WHY = "Code that runs text as a command or program is dangerous when any part of that text can come from a user."


def _by_title(f: Finding) -> Text | None:
    t = f.title
    loc = _loc(f)
    if t == "API key or token in source":
        return Text("A string that looks like an API key or token is in the code",
                    f"A value matching a known credential format is written directly in {loc}. (The value is hidden "
                    "in this report.)", "Secrets stored in code are copied with the code, so they spread to everyone "
                    "and every place the repository goes.", _SECRET_RISK, _SECRET_FIX,
                    "Check whether the credential-like values are real and rotate any that are")
    if t == "Private key committed to repository":
        return Text("A private key appears to be stored in the repository",
                    f"A private key block was found in {loc}. (Its contents are hidden.)",
                    "A private key proves identity. Anyone who has it can pretend to be you or your server.",
                    "If the key is real, someone could decrypt data or impersonate a service.",
                    "Treat it as compromised if it is real: generate a new key, replace it everywhere, and keep keys "
                    "outside the repository.", "Confirm whether the private key is real and replace it if so")
    if t == "Credentials embedded in URL":
        return Text("A password appears inside a connection address",
                    f"A web or database address in {loc} contains a username and password.",
                    "Addresses are logged, shared and copied freely, so a password inside one leaks easily.",
                    "If the password is real, someone with the repository could log in to that service.",
                    "Move the credentials into environment variables and build the address at runtime. Rotate the "
                    "password if it is real.", "Move connection passwords out of the code")
    if t == "Hardcoded credential-like value":
        return Text("A password-like value is written directly in the code",
                    f"A variable in {loc} that looks like a password, token or key is set to a fixed text value.",
                    "Fixed secrets in code are easy to leak and hard to change.",
                    "If it is a real secret, it could be misused by anyone who can read the code.",
                    _SECRET_FIX, "Check password-like values in the code and move real ones to environment variables")
    if t.startswith("Sensitive file not gitignored"):
        return Text("A secrets file is not protected from being committed",
                    f"{loc} usually holds secrets, and no `.gitignore` rule excludes it. Repo Doctor did not read "
                    "its contents.", "Files like this are easy to commit by accident.",
                    "If it contains real secrets and gets committed, they become visible to everyone with access.",
                    "Add the file name to `.gitignore`. If it was already committed, rotate its secrets and remove "
                    "it from history.", "Add secrets files to .gitignore")
    if t == "Use of eval()":
        return Text("The code runs text as code with eval()", f"`eval()` is called in {loc}.", _EXEC_WHY,
                    "If the text can be influenced by a user, they could make your program run their code.",
                    "Replace it with a safe alternative, such as `ast.literal_eval` or `JSON.parse`, or a lookup "
                    "table of allowed actions.", "Replace eval() with a safe alternative")
    if t == "Use of exec()":
        return Text("The code runs text as code with exec()", f"`exec()` is called in {loc}.", _EXEC_WHY,
                    "If the text can be influenced by a user, they could make your program run their code.",
                    "Avoid building and running code from text; call the specific functions you need instead.",
                    "Replace exec() with explicit function calls")
    if t in ("Shell command via os.system", "subprocess with shell=True", "Command execution via child_process"):
        return Text("A shell command is built and run by the program", f"{loc} runs a shell command.", _EXEC_WHY,
                    "If part of the command comes from user input, someone could add their own commands to it.",
                    "Pass the program and its arguments as a list (for example `subprocess.run([...])` or "
                    "`execFile`) instead of one string, and validate any input.", "Run commands without a shell")
    if t == "Unsafe deserialization (pickle)":
        return Text("Data is loaded with pickle", f"`pickle` loading is used in {loc}.",
                    "Pickle can run code while loading, so it is only safe for data you fully trust.",
                    "Loading a crafted file could run attacker-chosen code.",
                    "Use a data-only format such as JSON for anything that is not fully trusted.",
                    "Stop loading untrusted data with pickle")
    if t == "Possible SQL injection (string-built query)":
        return Text("A database query is built by joining text together",
                    f"A query in {loc} appears to be assembled with string formatting or concatenation.",
                    "If user input ends up inside the query text, it can change what the query does.",
                    "A crafted input could read or change data it should not be able to reach.",
                    "Use parameterised queries, for example `cursor.execute(sql, params)`.",
                    "Use parameterised database queries")
    if t == "Raw HTML injection sink":
        return Text("Content is written into the page as raw HTML", f"{loc} writes HTML directly into the page.",
                    "Raw HTML from an untrusted source can contain scripts that run in your users' browsers.",
                    "That is called cross-site scripting (XSS) and can expose user sessions or data.",
                    "Use `textContent`, or clean the HTML with a sanitiser such as DOMPurify first.",
                    "Avoid inserting raw HTML into pages")
    if t == "Syntax error":
        return Text("A file has a syntax error", f"Python could not read {loc}.",
                    "Code with a syntax error cannot run or be imported.",
                    "The feature that uses this file will fail as soon as it is loaded.",
                    "Fix the syntax at the line shown.", "Fix syntax errors")
    if t == "Bare except":
        return Text("Errors are caught without saying which kind", f"{loc} has an `except:` with no error type.",
                    "A catch-all hides real bugs and can even swallow Ctrl+C.",
                    "Problems could go unnoticed because the error disappears silently.",
                    "Catch the specific errors you expect (or `except Exception`) and log or handle them.",
                    "Catch specific errors instead of everything")
    if t == "Mutable default argument":
        return Text("A function reuses the same list or dictionary between calls",
                    f"A function in {loc} uses a list, dict or set as a default value.",
                    "Python creates that default once, so changes made in one call leak into the next.",
                    "The function could behave differently depending on earlier calls.",
                    "Use `None` as the default and create the list or dict inside the function.",
                    "Avoid mutable default arguments")
    if t == "Large function":
        return Text("A function is very long", f"A function in {loc} is longer than the guideline.",
                    "Long functions are harder to read, test and change safely.",
                    "Bugs are more likely to hide in code that is difficult to follow.",
                    "Split it into smaller functions that each do one thing.", "Break up very long functions")
    if t == "No automated tests found":
        return Text("No automated tests were found", "Repo Doctor looked for test files and configured test folders "
                    "and found none.", "Tests catch mistakes when code changes.",
                    "Changes could break behaviour without anyone noticing until users do.",
                    "Add a test suite (for example pytest or Jest), starting with the most important code.",
                    "Add a basic automated test suite")
    return None


_RUFF = {
    "F401": ("An import is never used", "Unused imports add clutter and can hide real dependencies.",
             "Remove the import."),
    "F841": ("A variable is assigned but never used", "Unused variables often point to leftover or incomplete code.",
             "Remove it, or use it."),
    "E722": ("Errors are caught without saying which kind", "A catch-all hides real bugs.",
             "Catch specific errors."),
    "B006": ("A function reuses the same list or dictionary between calls",
             "Python creates the default once, so changes leak between calls.",
             "Use `None` and create the object inside the function."),
    "F821": ("The code uses a name that is not defined", "This will raise an error when that line runs.",
             "Define or import the name, or fix the typo."),
    "F811": ("A name is defined twice", "The first definition is silently replaced, which is usually a mistake.",
             "Remove or rename one of them."),
}


def _by_category(f: Finding) -> Text | None:
    loc = _loc(f)
    cat = f.category
    if cat.startswith("quality/ruff-"):
        code = f.title.split(":", 1)[0].strip().upper()
        known = _RUFF.get(code)
        title, why, fix = known if known else (
            f"Ruff reported a code issue ({code})", "Ruff checks Python code for mistakes and style problems that "
            "can hide bugs.", "Follow the rule's guidance at the line shown.")
        return Text(title, f"Ruff rule {code} was triggered in {loc}.", why,
                    "Left alone, small issues like this tend to pile up and make real bugs harder to see.", fix,
                    f"Fix Ruff {code} issues")
    if cat.startswith("quality/eslint-"):
        return Text("ESLint reported a code issue", f"ESLint flagged {loc} (rule in the title).",
                    "ESLint checks JavaScript and TypeScript for mistakes that can hide bugs.",
                    "Left alone, issues like this can cause bugs or make code harder to maintain.",
                    "Follow the rule's guidance at the line shown.", "Fix ESLint issues")
    if cat.startswith("quality/tsc-"):
        return Text("TypeScript found a type problem", f"The TypeScript compiler reported an error in {loc}.",
                    "Type errors mean the code does not match its own declared types.",
                    "The code could fail at runtime in ways the types were meant to prevent.",
                    "Fix the type mismatch at the line shown.", "Fix TypeScript type errors")
    if cat.startswith("security/bandit-"):
        return Text("Bandit flagged a possible security weakness", f"Bandit reported a security check in {loc}.",
                    "Bandit looks for Python patterns that are often unsafe.",
                    "Depending on how this code is used, it might be exploitable.",
                    "Read the Bandit rule linked in the details and apply the recommended safer pattern.",
                    "Review Bandit security warnings")
    if cat.startswith("security/gitleaks-"):
        return Text("A secrets scanner found a possible credential", f"Gitleaks found something that looks like a "
                    f"secret in {loc}. (The value is hidden.)", "Secrets stored in code spread with the code.",
                    _SECRET_RISK, _SECRET_FIX, "Check Gitleaks secret findings and rotate real credentials")
    if cat.startswith("security/npm-audit-"):
        return Text("A JavaScript dependency has a known vulnerability", "`npm audit` reports a known security "
                    "advisory for a package this project uses.", "Known vulnerabilities are public, so attackers "
                    "know how to use them.", "Depending on how the package is used, the application might be "
                    "exposed to that weakness.", "Upgrade the package as suggested (check for breaking changes).",
                    "Upgrade vulnerable npm packages")
    if cat.startswith("testing/untested-module"):
        return Text("No test mentions this module", f"None of the test files refer to {loc}.",
                    "Code without tests is easier to break unnoticed. (It may still be tested in a way Repo Doctor "
                    "cannot see, so please check.)", "A future change could break it without any test failing.",
                    "Add tests for this module's main behaviour and error cases.", "Add tests for untested modules")
    return None


_AREA_WHY = {
    "quality": "Issues like this can make the code harder to maintain or hide bugs.",
    "security": "Security weaknesses can let someone misuse the application or its data, depending on how this code "
                "is reached.",
    "testing": "Gaps in tests make it easier for future changes to break behaviour without anyone noticing.",
}
_AREA_RISK = {
    "quality": "Over time this can slow development and let bugs through.",
    "security": "Whether it is exploitable depends on how the code is used; it is worth a look.",
    "testing": "A change could break this behaviour without a failing test to warn you.",
}


def explain(f: Finding) -> Text:
    """Plain-language text for a finding: curated text if we know the check, otherwise the finding's own words."""
    known = _by_title(f) or _by_category(f)
    area = f.category.split("/")[0]
    if known:
        fix = f.suggested_fix.strip() or known.fix
        return Text(known.title, known.what, known.why, known.risk, fix, known.action)
    desc = re.sub(r"\s+", " ", f.description).strip() or f.title
    return Text(f.title, desc, _AREA_WHY.get(area, "This may affect the quality or safety of the project."),
                _AREA_RISK.get(area, "Worth reviewing."),
                f.suggested_fix.strip() or "Review the code shown and decide whether a change is needed.",
                f"Review: {f.title}")
