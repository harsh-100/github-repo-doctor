def e(text: object) -> str:
    return escape(str(text), quote=True)


def inline(text: str) -> str:
    """Escape, then allow only `code` and **bold** (generated by us or the model, never raw HTML)."""
    out = e(text)
    out = _INLINE_CODE.sub(lambda m: f"<code>{m.group(1)}</code>", out)
    return _BOLD.sub(lambda m: f"<strong>{m.group(1)}</strong>", out)


def mini_markdown(text: str) -> str:
    """Tiny, safe Markdown subset for the AI-written summary: headings, bullets, paragraphs."""
    html, in_list = [], False
    for raw in text.splitlines():
        line = raw.rstrip()
        bullet = re.match(r"^\s*[-*]\s+(.*)", line)
        if in_list and not bullet:
            html.append("</ul>")
            in_list = False
        if not line.strip():
            continue
        if line.startswith("#"):
            html.append(f"<h4>{inline(line.lstrip('# ').strip())}</h4>")
        elif bullet:
            if not in_list:
                html.append("<ul>")
                in_list = True
            html.append(f"<li>{inline(bullet.group(1))}</li>")
        else:
            html.append(f"<p>{inline(line)}</p>")
    if in_list:
        html.append("</ul>")
    return "".join(html)


