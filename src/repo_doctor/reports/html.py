def _vscode_link(root: str, path: str, line: int | None) -> str:
    target = f"{root.rstrip('/')}/{path}" + (f":{line}" if line else "")
    return "vscode://file/" + quote(target, safe="/:")


def _finding_html(data: ReportData, f: Finding) -> str:
    t = data.text_for(f.id)
    area = f.category.split("/")[0]
    loc = (f.file_path or "") + (f":{f.line}" if f.line else "")
    copy_text = redact("\n".join(filter(None, [
        f"{f.id} [{SEV_LABEL[f.severity.value]}] {t.title}", f"Location: {loc}" if loc else "",
        f"Status: {t.verification_label} (confidence {round(f.confidence * 100)}%)", f"What: {t.what}",
        f"Why it matters: {t.why}", f"How to fix: {t.fix}", f"Evidence: {f.evidence}" if f.evidence else ""])))
    parts = [f'<article class="finding sev-{f.severity.value}" id="{e(f.id.lower())}" data-severity="{f.severity.value}" '
             f'data-area="{e(area)}"><details><summary>'
             f'<span class="badge {f.severity.value}">{SEV_LABEL[f.severity.value]}</span>'
             f'<span class="badge ver {e(t.verification_label)}" title="{e(t.verification_meaning)}">{e(t.verification_label)}</span>'
             f'<span class="ftitle">{e(t.title)}</span>' + (f'<span class="floc">{e(loc)}</span>' if loc else "") +
             '</summary><div class="fbody">']
    if t.context:
        parts.append(f'<div class="callout ctx"><strong>Context:</strong> {e(t.context)}</div>')
    parts.append(f"<dl><dt>What we found</dt><dd>{inline(t.what)}</dd><dt>Why it matters</dt><dd>{inline(t.why)}</dd>"
                 f"<dt>What could happen</dt><dd>{inline(t.risk)}</dd><dt>How to fix it</dt><dd>{inline(t.fix)}</dd>")
    if f.suggested_fix and f.suggested_fix != t.fix:
        parts.append(f"<dt>Suggested fix</dt><dd>{inline(f.suggested_fix)}</dd>")
    if f.explanation:
        parts.append(f"<dt>Plain-language note (AI)</dt><dd>{inline(f.explanation)}</dd>")
    parts.append("</dl>")
    parts.append(f'<p class="meaning">{e(t.verification_meaning)} Confidence {round(f.confidence * 100)}%.'
                 + (f" Reviewer note: {e(f.review_note)}" if f.review_note else "") + "</p>")
    if f.evidence:
        parts.append(f'<details class="evidence"><summary>Technical evidence</summary><pre>{e(redact(f.evidence))}</pre>'
                     f'<p class="muted">{e(f.description)}</p>'
                     f'<p class="muted">Found by {e(f.agent)} · category <code>{e(f.category)}</code></p></details>')
    actions = [f'<button class="btn" type="button" data-copy="{e(copy_text)}">Copy details</button>']
    if f.file_path:
        actions.append(f'<button class="btn" type="button" data-copy="{e(loc)}">Copy path</button>')
        if data.project.root:  # remote (GitHub) analyses have no local checkout to open
            actions.append(f'<a class="btn" href="{e(_vscode_link(data.project.root, f.file_path, f.line))}">Open in VS Code</a>')
    parts.append(f'<div class="factions">{"".join(actions)}</div></div></details></article>')
    return "".join(parts)


def _area_html(data: ReportData, area: str, intro: str, extra_html: str = "") -> str:
    items = [f for f in data.result.findings if f.category.split("/")[0] == area]
    if items:
        rows = "".join(
            f'<tr><td><a href="#{e(f.id.lower())}">{e(f.id)}</a></td><td><span class="badge {f.severity.value}">'
            f"{SEV_LABEL[f.severity.value]}</span></td><td>{e(data.text_for(f.id).title)}</td>"
            f'<td class="muted">{inline(data.text_for(f.id).location) or "-"}</td></tr>' for f in items)
        table = (f'<div class="tablewrap"><table><caption class="muted">{e(AREA_TITLES[area])} findings</caption>'
                 f'<thead><tr><th scope="col">ID</th><th scope="col">Severity</th><th scope="col">What</th>'
                 f'<th scope="col">Where</th></tr></thead><tbody>{rows}</tbody></table></div>')
    else:
        table = '<p class="muted">Nothing was reported in this area by the checks that ran.</p>'
    return f"<p>{e(intro)}</p>{table}{extra_html}"


