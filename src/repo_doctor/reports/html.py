def render_dashboard(project_name: str, remote: str | None, runs: list[dict]) -> str:
    """Project history page from the runs' metadata.json files (oldest first in `runs`)."""
    hidden = len([r for r in runs if r.get("provisional")])
    runs = [r for r in runs if not r.get("provisional")]  # unfinished (provisional) runs stay on disk but are not history
    latest = runs[-1] if runs else None
    comparable = [r for r in runs if r.get("mode") == "analyze"]
    trend = charts.trend_chart(comparable[-12:]) if len(comparable) >= 2 else ""

    def delta(m: dict) -> str:
        same = [r for r in runs if r.get("mode") == m.get("mode")]
        idx = same.index(m)
        if idx == 0:
            return "first run"
        prev = same[idx - 1]
        bits = []
        for k in ("critical", "high", "medium", "low"):
            d = m["counts"].get(k, 0) - prev["counts"].get(k, 0)
            if d:
                bits.append(f"{d:+d} {k}")
        return ", ".join(bits) or "no change"

    rows = "".join(
        f'<tr><td>{e(m["created_at"][:16].replace("T", " "))} UTC<br><span class="muted"><code>{e(m["run_id"])}</code></span></td>'
        f'<td>{e(SCOPE.get(m.get("mode", ""), m.get("mode", "")))}</td>'
        f'<td><span class="pill {HEALTH_CLASS.get(m.get("health", ""), "warn")}" style="margin:0">{e(m.get("health", ""))}</span></td>'
        f'<td>{m["counts"].get("critical", 0)} / {m["counts"].get("high", 0)} / {m["counts"].get("medium", 0)} / {m["counts"].get("low", 0)}</td>'
        f'<td class="muted">{e(delta(m))}</td>'
        f'<td><a href="runs/{e(m["run_id"])}/report.html">HTML</a> · <a href="runs/{e(m["run_id"])}/report.md">Markdown</a> · '
        f'<a href="runs/{e(m["run_id"])}/findings.json">JSON</a></td></tr>' for m in reversed(runs))
    table = (f'<div class="tablewrap"><table><caption class="muted">Analysis runs, newest first. Counts are critical / high / medium / low.</caption>'
             f'<thead><tr><th scope="col">Run</th><th scope="col">Mode</th><th scope="col">Health</th><th scope="col">C / H / M / L</th>'
             f'<th scope="col">Change vs previous {e("same-mode")} run</th><th scope="col">Reports</th></tr></thead><tbody>{rows}</tbody></table></div>'
             if runs else '<p class="muted">No analyses yet.</p>')
    last = (f'<p>Last analysed {e(latest["created_at"][:16].replace("T", " "))} UTC · {len(runs)} run(s)</p>'
            f'<span class="pill {HEALTH_CLASS.get(latest.get("health", ""), "warn")}">Latest: {e(latest.get("health", ""))}</span>'
            if latest else "")
    trend_html = (f'<section><h2>Trend</h2><div class="panel">{trend}<p class="muted">Compares full-analysis runs only, '
                  f"oldest to newest.</p></div></section>" if trend else "")
    body = f"""<header class="topbar"><div class="in"><span class="brand">Repo <span>Doctor</span></span>
<span class="crumb">{e(project_name)} · project history</span><span class="spacer"></span>
<button class="btn" id="theme" type="button" aria-label="Toggle light or dark theme">Theme</button></div></header>
<main id="main"><section class="hero"><h1>{e(project_name)}</h1>
<p>Every analysis of this project is kept. Older reports are never overwritten.</p>
{('<p class="muted">' + str(hidden) + ' provisional run(s) written while model answers were pending are on disk but not listed.</p>') if hidden else ''}{('<p>Repository: ' + e(remote) + '</p>') if remote else ''}{last}</section>
{trend_html}<section><h2>Analysis runs</h2>{table}</section></main>
<footer><div style="max-width:1080px;margin:0 auto;padding:0 16px 24px">Generated by Repo Doctor.</div></footer>"""
    return _page(f"Repo Doctor: {project_name}", body, _THEME_JS)
